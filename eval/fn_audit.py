"""
False-Negative Audit Tool for ThreatMap Lite.
Module: PDF Processing & IOC Intelligence

Facilitates independent human inspection of source PDF pages to discover
and record threat indicators missed by both the production extractor and
automated regex discovery (ensuring genuine False Negatives are captured).

CRITICAL METHODOLOGICAL PRINCIPLE:
Recall CANNOT be measured solely from candidates generated by the extractor.
Human reviewers must inspect original PDF pages independently to find missed
adversary indicators and record them into the ground-truth review queue.

Usage:
    # 1. Inspect a specific report page-by-page in terminal:
    python -m eval.fn_audit --report cisa_aa22_187a_maui_ransomware.pdf --page 1

    # 2. Generate a False-Negative Audit Worksheet (Markdown):
    python -m eval.fn_audit --subset --output eval/fn_audit_worksheet.md

    # 3. Record a manually discovered IOC into the review queue:
    python -m eval.fn_audit --add-ioc --queue eval/review_queue_subset.csv \
        --report cisa_aa22_187a_maui_ransomware.pdf --page 2 \
        --type md5 --raw "5d41402abc4b2a76b9719d911017c592" \
        --evidence "Dropped malware sample in system directory" \
        --notes "Missed by automated discovery"
"""

import argparse
import csv
import sys
from pathlib import Path
from typing import Any

# Ensure project root is on sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from backend.app.services.pdf_service import PageText, extract_pages
from eval.generate_review_queue import (
    CSV_FIELDNAMES,
    REPRESENTATIVE_SUBSET,
    compute_review_priority_and_hint,
    validate_candidate_format,
)
from eval.ioc_eval import SUPPORTED_IOC_TYPES, normalize_ground_truth_value


def inspect_page_for_audit(
    pdf_path: Path,
    page_number: int,
    known_candidates: list[dict[str, Any]] | None = None,
) -> None:
    """
    Displays page text alongside previously captured indicators to help the
    reviewer identify any indicators that were missed.
    """
    pages = extract_pages(pdf_path)
    if not pages or page_number < 1 or page_number > len(pages):
        print(f"[!] Invalid page {page_number}. PDF has {len(pages)} pages.", file=sys.stderr)
        return

    page_data = pages[page_number - 1]
    raw_text = page_data.get("page_text") or page_data.get("text") or ""

    print("=" * 80)
    print(f" FALSE-NEGATIVE AUDIT: {pdf_path.name} | Page {page_number} of {len(pages)}")
    print("=" * 80)
    print("\nPAGE TEXT CONTENT:")
    print("-" * 80)
    for idx, line in enumerate(raw_text.splitlines(), start=1):
        if line.strip():
            print(f" {idx:3d} | {line}")
    print("-" * 80)

    # Filter known candidates for this page
    if known_candidates:
        page_known = [
            c for c in known_candidates
            if c.get("report_filename") == pdf_path.name and int(c.get("source_page", 0)) == page_number
        ]
        print(f"\nCURRENTLY DETECTED ON THIS PAGE ({len(page_known)} candidates):")
        for k in page_known:
            origin = k.get("source_origin", "unknown")
            print(f" - [{k['ioc_type'].upper()}] {k['normalized_value']} (origin: {origin})")
    print("=" * 80)
    print(" AUDITOR CHECKLIST: Are there any missed adversary IPs, domains, hashes, or CVEs?")
    print(" If found, record with: python -m eval.fn_audit --add-ioc ...")
    print("=" * 80)


def add_manual_ioc_to_queue(
    queue_csv: Path,
    pdf_dir: Path,
    report: str,
    page_number: int,
    ioc_type: str,
    raw_value: str,
    evidence: str,
    notes: str,
    label: str = "true_ioc",
) -> None:
    """
    Appends a manually discovered indicator to the review queue with source_origin='manual_inspection'.
    """
    if ioc_type not in SUPPORTED_IOC_TYPES:
        raise ValueError(f"Invalid ioc_type '{ioc_type}'. Must be one of: {SUPPORTED_IOC_TYPES}")

    pdf_path = pdf_dir / report
    if not pdf_path.is_file():
        raise FileNotFoundError(f"Source PDF not found: {pdf_path.resolve()}")

    norm_value = normalize_ground_truth_value(ioc_type, raw_value)
    is_valid, reason = validate_candidate_format(ioc_type, raw_value, norm_value)
    prio = "HIGH: Manually Discovered Indicator (Independent Audit)"
    hint = "Discovered during independent page inspection. Verify ground-truth attribution."

    # Extract surrounding context from page
    pages = extract_pages(pdf_path)
    surrounding = evidence
    if pages and 1 <= page_number <= len(pages):
        page_lines = (pages[page_number - 1].get("page_text") or "").splitlines()
        for idx, line in enumerate(page_lines):
            if raw_value in line or norm_value in line:
                start_l = max(0, idx - 2)
                end_l = min(len(page_lines), idx + 3)
                surrounding = " // ".join(l.strip() for l in page_lines[start_l:end_l] if l.strip())
                break

    new_row = {
        "report_filename": report,
        "source_page": page_number,
        "ioc_type": ioc_type,
        "raw_candidate": raw_value,
        "normalized_value": norm_value,
        "source_origin": "manual_inspection",
        "format_valid": reason,
        "review_priority": prio,
        "review_hint": hint,
        "label": label,
        "context_snippet": evidence,
        "surrounding_context": surrounding,
        "reviewer_notes": notes,
    }

    # Load existing rows or create new queue
    rows: list[dict[str, Any]] = []
    if queue_csv.is_file():
        with open(queue_csv, newline="", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            rows = list(reader)

    # Check for duplicate
    dup = any(
        r["report_filename"] == report
        and int(r["source_page"]) == page_number
        and r["ioc_type"] == ioc_type
        and r["normalized_value"] == norm_value
        for r in rows
    )
    if dup:
        print(f"[!] Candidate {ioc_type}:{norm_value} already exists on page {page_number} of {report}.", file=sys.stderr)
        return

    rows.append(new_row)

    queue_csv.parent.mkdir(parents=True, exist_ok=True)
    with open(queue_csv, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_FIELDNAMES)
        writer.writeheader()
        writer.writerows(rows)

    print(f"[+] Successfully appended manually discovered IOC to {queue_csv}:")
    print(f"    Report: {report} | Page: {page_number}")
    print(f"    Type: {ioc_type} | Normalized: {norm_value}")
    print(f"    Label: {label} | Origin: manual_inspection")


def generate_fn_audit_worksheet(
    pdf_dir: Path,
    report_filenames: list[str],
    output_md: Path,
) -> None:
    """
    Generates a False-Negative Audit Worksheet in Markdown format to guide
    human analysts through an independent manual review of each PDF page.
    """
    lines = [
        "# ThreatMap Lite - Independent False-Negative Audit Worksheet",
        "",
        "**Methodological Purpose:**",
        "Recall cannot be measured from extractor predictions alone. Reviewers must inspect",
        "actual PDF pages to locate threat indicators that automated tools overlooked.",
        "",
        "## Audit Instructions:",
        "1. For each page listed below, read the page text and check for adversary infrastructure.",
        "2. If you find an IOC that is NOT listed under 'Currently Captured', record it with:",
        "   ```powershell",
        "   python -m eval.fn_audit --add-ioc --queue eval/review_queue_subset.csv \\",
        "       --report <filename> --page <page_num> --type <type> --raw \"<value>\" \\",
        "       --evidence \"<snippet>\" --notes \"<justification>\"",
        "   ```",
        "",
        "---",
        "",
    ]

    for fn in report_filenames:
        pdf_path = pdf_dir / fn
        if not pdf_path.is_file():
            continue
        pages = extract_pages(pdf_path)
        lines.append(f"## Report: `{fn}` ({len(pages)} pages)")
        lines.append("")
        for p in pages:
            p_num = p["page_number"]
            text = (p.get("page_text") or "").strip()
            lines.append(f"### Page {p_num}")
            lines.append("```text")
            # Truncate text to first 1200 chars for sheet readability
            lines.append(text[:1200] + ("\n... [truncated for worksheet]" if len(text) > 1200 else ""))
            lines.append("```")
            lines.append("- [ ] **Audited:** Checked for unextracted IPs, domains, hashes, URLs, and CVEs.")
            lines.append("- **Auditor Notes / Discovered IOCs:** ________________________________________")
            lines.append("")
        lines.append("---")
        lines.append("")

    output_md.parent.mkdir(parents=True, exist_ok=True)
    with open(output_md, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"[+] Successfully generated False-Negative Audit Worksheet: {output_md}")


def main() -> None:
    parser = argparse.ArgumentParser(description="False-Negative Audit Tool for independent manual IOC discovery.")
    parser.add_argument("--pdf-dir", type=Path, default=PROJECT_ROOT / "eval" / "raw_reports", help="Directory of raw PDF reports.")
    parser.add_argument("--report", type=str, help="Report filename to inspect.")
    parser.add_argument("--page", type=int, default=1, help="Page number to inspect.")
    parser.add_argument("--queue", type=Path, default=PROJECT_ROOT / "eval" / "review_queue_subset.csv", help="Review queue CSV path.")
    parser.add_argument("--subset", action="store_true", help="Audit the representative 3-report subset.")
    parser.add_argument("--output", type=Path, help="Output path for Markdown worksheet.")

    # Manual IOC addition args
    parser.add_argument("--add-ioc", action="store_true", help="Record a manually discovered IOC.")
    parser.add_argument("--type", type=str, help="IOC type for manual addition.")
    parser.add_argument("--raw", type=str, help="Raw candidate string for manual addition.")
    parser.add_argument("--evidence", type=str, default="", help="Context snippet for manual addition.")
    parser.add_argument("--notes", type=str, default="Manually discovered during page inspection", help="Reviewer notes.")
    parser.add_argument("--label", type=str, default="true_ioc", help="Initial label for manual addition.")

    args = parser.parse_args()

    if args.add_ioc:
        if not args.report or not args.type or not args.raw:
            print("[!] Error: --add-ioc requires --report, --type, and --raw.", file=sys.stderr)
            sys.exit(1)
        add_manual_ioc_to_queue(
            args.queue,
            args.pdf_dir,
            args.report,
            args.page,
            args.type,
            args.raw,
            args.evidence,
            args.notes,
            label=args.label,
        )
        return

    if args.subset and args.output:
        generate_fn_audit_worksheet(args.pdf_dir, list(REPRESENTATIVE_SUBSET), args.output)
        return

    if args.report:
        pdf_path = args.pdf_dir / args.report
        known: list[dict[str, Any]] = []
        if args.queue.is_file():
            with open(args.queue, newline="", encoding="utf-8") as f:
                known = list(csv.DictReader(f))
        inspect_page_for_audit(pdf_path, args.page, known_candidates=known)
        return

    parser.print_help()


if __name__ == "__main__":
    main()
